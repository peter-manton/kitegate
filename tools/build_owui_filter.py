"""Build the single-file Open WebUI filter from the package and the adapter.

Open WebUI functions are pasted in as one file, and most installs cannot pip
install extra packages, so the policy package is inlined. The engine stays the
same code as every other adapter; only the packaging differs.

    python tools/build_owui_filter.py          # writes dist/kitegate_openwebui_filter.py
    python tools/build_owui_filter.py --check  # fails if dist is out of date
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PKG = ROOT / "src" / "kitegate"
sys.path.insert(0, str(ROOT / "src"))
from kitegate.signing import (SIGNATURE_SUFFIX, PackTrust, Signature,  # noqa: E402
                                      SignatureError)
SOURCE = ROOT / "adapters" / "openwebui" / "kitegate_filter.py"
OUT = ROOT / "dist" / "kitegate_openwebui_filter.py"
MARKER = "# kitegate:inline"


def module_body(path: Path) -> str:
    """One package module, stripped of the things an inlined copy cannot have.

    Shared with tools/build_owui_photo.py, which inlines a different subset of
    the package into the photo tool.
    """
    text = path.read_text(encoding="utf-8")
    text = re.sub(r'^""".*?"""\n', "", text, count=1, flags=re.S)       # module docstring
    text = re.sub(r"^from __future__ import annotations\n", "", text, flags=re.M)
    text = re.sub(r"^from \.\w* ?import .*\n", "", text, flags=re.M)      # relative imports
    return f"# ---- inlined from src/kitegate/{path.name} ----\n{text.strip()}\n"


def splice(source: str, inlined: str, builder: str, edit: str) -> str:
    """Replace the first marked import with the inlined package.

    Any further marked imports are submodules already covered by it, so they
    are dropped.
    """
    if MARKER not in source:
        raise SystemExit(f"marker '{MARKER}' not found")
    out, done = [], False
    for number, line in enumerate(source.splitlines(keepends=True), start=1):
        if MARKER in line:
            # A marked import must be a single line. Only the marked line is
            # dropped, so a bracketed continuation would be left behind as a
            # stray indented fragment and the built file would not parse.
            # Caught here rather than at paste time in Open WebUI.
            if line.rstrip().rstrip(",").endswith(("(", "\\")) or line.count("(") > line.count(")"):
                raise SystemExit(
                    f"line {number}: a '{MARKER}' import must fit on one line; "
                    "split it into several marked imports instead")
            if not done:
                out.append(inlined)
                done = True
            continue
        out.append(line)
    built = "".join(out)
    # Keep the frontmatter docstring first, add the generated notice after it.
    end = built.index('"""', 3) + 3
    notice = (f"\n# GENERATED by {builder}. Do not edit; edit the package"
              f"\n# and {edit}, then rebuild.\n")
    # No `from __future__ import annotations` here, deliberately: Open WebUI
    # execs the file without registering it in sys.modules, and dataclasses
    # with string annotations then fail looking the module up.
    return built[:end] + notice + built[end:]


def build() -> str:
    source = SOURCE.read_text(encoding="utf-8")

    parts = [module_body(PKG / name)
             for name in ("core.py", "signing.py", "packs.py", "engine.py", "messages.py")]
    packs = {}
    for p in sorted((PKG / "packs").glob("*.yaml")):
        text = p.read_text(encoding="utf-8")
        # Embedded packs are not checked again at run time, so check them here.
        sig = p.with_name(p.name + SIGNATURE_SUFFIX)
        if not sig.is_file():
            raise SystemExit(f"{p}: not signed; run kitegate-pack sign")
        try:
            PackTrust.bundled().check(text, Signature.from_text(sig.read_text(encoding="ascii")), str(p))
        except SignatureError as exc:
            raise SystemExit(f"refusing to embed: {exc}") from None
        packs[p.stem] = text
    parts.append("_EMBEDDED.update(" + repr(packs) + ")\n")
    return splice("".join(source), "\n".join(parts), "tools/build_owui_filter.py",
                  "adapters/openwebui/kitegate_filter.py")


def main() -> None:
    built = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != built:
            raise SystemExit("dist/kitegate_openwebui_filter.py is out of date: run tools/build_owui_filter.py")
        print("up to date")
        return
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(built, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(built.splitlines())} lines)")


if __name__ == "__main__":
    main()
